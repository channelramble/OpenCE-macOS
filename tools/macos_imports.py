#!/usr/bin/env python3
"""Generate the macOS guest image's host import stubs.

As the Android guest's (tools/android_imports.py): every function the guest
imports from the host gets a stub that loads the host's 64-bit function
address from __host_import_table and branches to it. The macOS guest's
addresses are not the host's, though (port/macos/README.md): before the
branch, each pointer argument of a function declared in the given headers is
widened to the host address of the guest memory it points at, x28 (the
window's base) plus the guest address; a NULL stays NULL. The OpenGL ES and
posix_* imports (hostgl_*, hostposix_*) are called from generated wrappers
that widen their own pointers (tools/android_gl_stubs.py and
tools/android_posix_stubs.py --window), and pass through.

The stubs are not rewritten by tools/macos_sfi.py: they are the one place
guest code jumps to host addresses.

Usage: macos_imports.py [--host-table table.c] [--header guest_host.h]... output.s list...
"""

import re
import sys

INTEGER_REGISTERS = 8
FLOAT_TYPES = {"float", "double"}


def prototypes(headers):
    """name -> parameter types, for the host_* functions the headers declare"""
    result = {}
    for path in headers:
        text = open(path, encoding="utf-8").read()
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        text = re.sub(r"//[^\n]*", " ", text)
        text = re.sub(r"__attribute__\s*\(\(.*?\)\)", " ", text)
        text = " ".join(text.split())
        for name, params in re.findall(r"\b(host_\w+)\s*\(([^()]*)\)\s*;", text):
            params = params.strip()
            result[name] = [] if params in ("", "void") else [p.strip() for p in params.split(",")]
    return result


def pointer_registers(params):
    """the integer argument registers holding pointers"""
    registers = []
    integer = 0
    for param in params:
        base = re.sub(r"\b(const|volatile|unsigned|signed)\b", " ", param)
        words = base.replace("*", " * ").split()
        if "*" not in words and words and words[0] in FLOAT_TYPES:
            continue
        if integer >= INTEGER_REGISTERS:
            raise SystemExit(f"a parameter on the stack: {param}")
        if "*" in words:
            registers.append(integer)
        integer += 1
    return registers


def main():
    arguments = sys.argv[1:]
    host_table = None
    headers = []
    while arguments and arguments[0].startswith("--"):
        if arguments[0] == "--host-table":
            host_table = arguments[1]
        elif arguments[0] == "--header":
            headers.append(arguments[1])
        else:
            raise SystemExit(f"unknown option {arguments[0]}")
        arguments = arguments[2:]
    output, lists = arguments[0], arguments[1:]
    names = []
    for path in lists:
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line and line not in names:
                names.append(line)
    declared = prototypes(headers)
    missing = [name for name in names if not name.startswith(("hostgl_", "hostposix_")) and name not in declared]
    if missing:
        raise SystemExit("imports without a declaration in the headers: " + ", ".join(missing))

    out = ["/* generated by tools/macos_imports.py; do not edit */", "\t.text"]
    for index, name in enumerate(names):
        offset = index * 8
        out += [
            f"\t.globl {name}",
            f"\t.type {name},%function",
            "\t.p2align 2",
            f"{name}:",
        ]
        for register in pointer_registers(declared.get(name, [])):
            label = f".L{name}_{register}"
            out += [
                f"\tcbz w{register}, {label}",
                f"\tadd x{register}, x28, w{register}, uxtw",
                f"{label}:",
            ]
        out += [
            f"\tadrp x16, __host_import_table+{offset}",
            f"\tldr x16, [x16, :lo12:__host_import_table+{offset}]",
            "\tbr x16",
        ]
    out += [
        "\t.section .rodata",
        "\t.globl __host_import_names",
        "__host_import_names:",
    ]
    out += [f'\t.asciz "{name}"' for name in names]
    out += [
        "\t.p2align 2",
        "\t.globl __host_import_count",
        "__host_import_count:",
        f"\t.long {len(names)}",
        "\t.data",
        "\t.p2align 3",
        "\t.globl __host_import_table",
        "__host_import_table:",
        f"\t.zero {max(len(names), 1) * 8}",
    ]
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    if host_table:
        host_names = [n for n in names if not n.startswith("hostgl_")]

        def symbol(n):
            # hostposix_<name> imports port/linux/src/posix.h's posix_<name>
            return "posix_" + n[len("hostposix_"):] if n.startswith("hostposix_") else n

        table = ["/* generated by tools/macos_imports.py; do not edit */", "#include <string.h>", ""]
        table += [f"extern void {symbol(n)}(void);" for n in host_names]
        table += ["", "static const struct { const char *name; void *function; } imports[] =", "{"]
        table += [f'\t{{ "{n}", (void *){symbol(n)} }},' for n in host_names]
        table += ["};", "",
                  "void *host_resolve_import(const char *name)",
                  "{",
                  "\tunsigned long index;",
                  "",
                  "\tfor (index = 0; index < sizeof(imports) / sizeof(imports[0]); index++)",
                  "\t{",
                  "\t\tif (!strcmp(imports[index].name, name))",
                  "\t\t\treturn imports[index].function;",
                  "\t}",
                  "\treturn NULL;",
                  "}"]
        with open(host_table, "w", encoding="utf-8") as f:
            f.write("\n".join(table) + "\n")


if __name__ == "__main__":
    main()
